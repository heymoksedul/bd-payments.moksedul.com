/**
 * Post-process the raw Tailwind build so the whole stylesheet is namespaced
 * under `.bd-payments-scope`.
 *
 * Tailwind emits bare utilities (`.flex`, `.p-4`) that would collide with — or
 * be overridden by — the host application's own CSS. We prefix every rule with
 * the scope class so the payment dialog looks identical no matter what design
 * system it is dropped into, and so it never leaks styles back out.
 *
 * Output:
 *   dist/index.css   – the scoped stylesheet (for a plain `import "..."`)
 *   src/styles.ts    – the same CSS as an exported string, injected at runtime
 *                      by <BdPaymentProvider> so consumers don't have to wire up
 *                      a CSS import at all.
 */
const fs = require("node:fs");
const path = require("node:path");
const postcss = require("postcss");

const SCOPE = ".bd-payments-scope";
const PKG = path.resolve(__dirname, "..");
const RAW = path.join(PKG, "dist", "index.raw.css");
const OUT_CSS = path.join(PKG, "dist", "index.css");
const OUT_TS = path.join(PKG, "src", "styles.ts");

/** Split a selector list on top-level commas only (ignoring commas in `:is()` etc.). */
function splitTopLevel(selector) {
  const parts = [];
  let depth = 0;
  let current = "";
  for (const ch of selector) {
    if (ch === "(" || ch === "[") depth++;
    else if (ch === ")" || ch === "]") depth--;
    if (ch === "," && depth === 0) {
      parts.push(current);
      current = "";
    } else {
      current += ch;
    }
  }
  if (current) parts.push(current);
  return parts;
}

function scopeSelector(selector) {
  return splitTopLevel(selector)
    .map((part) => {
      const s = part.trim();
      if (!s) return s;
      // Already scoped (our own variable / animation blocks) — leave untouched.
      if (s.includes("bd-payments-scope")) return s;
      // Bare `:root` becomes the scope root itself.
      if (s === ":root") return SCOPE;
      return `${SCOPE} ${s}`;
    })
    .join(", ");
}

/** A plain-function PostCSS plugin that scopes every style rule. */
function scopePlugin(root) {
  root.walkRules((rule) => {
    // Skip @keyframes steps (`from`, `50%`, ...) — they are not selectors.
    const parent = rule.parent;
    if (parent && parent.type === "atrule" && /keyframes$/i.test(parent.name)) {
      return;
    }
    rule.selector = scopeSelector(rule.selector);
  });
}

async function main() {
  if (!fs.existsSync(RAW)) {
    console.error(`[build-css] missing ${RAW} — run the Tailwind build first.`);
    process.exit(1);
  }
  const raw = fs.readFileSync(RAW, "utf8");
  const { css } = await postcss([scopePlugin]).process(raw, { from: undefined });

  fs.writeFileSync(OUT_CSS, css, "utf8");

  const literal = "`" + css.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";
  const ts =
    "// AUTO-GENERATED by scripts/build-css.js — do not edit by hand.\n" +
    "// The scoped stylesheet, injected at runtime by <BdPaymentProvider>.\n" +
    `export const cssString = ${literal};\n`;
  fs.writeFileSync(OUT_TS, ts, "utf8");

  // The raw file is an intermediate artifact.
  fs.rmSync(RAW, { force: true });

  console.log(
    `[build-css] scoped ${css.length.toLocaleString()} bytes → dist/index.css + src/styles.ts`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
